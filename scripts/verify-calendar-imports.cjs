app.whenReady().then(() => session.defaultSession.protocol.handle('https', request => {
  const url = new URL(request.url)
  if (url.hostname !== 'school.dayweave.test') return new Response(null, { status: 404 })
  requests.set(url.pathname, (requests.get(url.pathname) || 0) + 1)
  if (url.pathname === '/calendar') return new Response(calendarFixture, { headers: { 'content-type': 'application/octet-stream' } })
  if (url.pathname === '/unsupported') return new Response('{"type":"unsupported"}', { headers: { 'content-type': 'application/json' } })
  if (url.pathname === '/missing') return new Response(null, { status: 404 })
  if (url.pathname === '/forbidden') return new Response(null, { status: 403 })
  if (url.pathname === '/download') return new Response(Buffer.from(pdfFixture(), 'base64'), { headers: { 'content-type': 'application/octet-stream', 'content-disposition': 'attachment; filename="campus.pdf"' } })
  return new Response('<!DOCTYPE html><html><body>School login</body></html>', { headers: { 'content-type': 'text/html' } })
}))
